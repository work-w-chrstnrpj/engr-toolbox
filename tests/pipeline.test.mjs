import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { templateRoot, tempDir, write, gitInit } from './helpers.mjs';
import { initialState, reduce, result, render } from '../lib/prompt.mjs';
import { resolvePipeline, renderPipeline, writePipeline, readVersion, releaseNotes, WORKFLOW_FILES } from '../lib/pipeline.mjs';
import { installAssets } from '../lib/install.mjs';

const cli = path.join(templateRoot, 'bin', 'cli.mjs');
const keys = (state, ...names) => names.reduce((s, n) => reduce(s, { name: n }), state);
const tools = ['claude', 'codex', 'cursor', 'opencode'].map(value => ({ value }));

describe('pickers', () => {
  test('multi-select: move, toggle several, confirm', () => {
    const s = keys(initialState(tools, { multi: true }), 'space', 'down', 'down', 'down', 'space', 'return');
    assert.equal(s.done, true);
    assert.deepEqual(result(s), ['claude', 'opencode']);
  });

  test('multi-select: preselected, a = all, n = none, cannot confirm empty', () => {
    let s = initialState(tools, { multi: true, selected: ['codex'] });
    assert.deepEqual(result(keys(s, 'return')), ['codex']);
    assert.equal(result(keys(s, 'a', 'return')).length, 4);
    s = keys(s, 'n', 'return');
    assert.equal(s.done, false);
    assert.match(s.error, /at least one/);
  });

  test('select: arrows wrap, enter picks, escape cancels; render marks choices', () => {
    const s = initialState(tools, { selected: ['cursor'] });
    assert.equal(result(keys(s, 'down', 'down', 'return')), 'claude', 'wraps around');
    assert.equal(result(keys(s, 'escape')), null);
    const lines = render('Tools?', keys(initialState(tools, { multi: true }), 'space'));
    assert.match(lines[2], /❯ ◉ claude/);
    assert.match(lines[3], /  ◯ codex/);
  });
});

describe('pipeline', () => {
  test('test mode: checks on PRs into develop and main, and on push to develop; no release', () => {
    const root = tempDir();
    write(root, 'package.json', '{"version":"1.0.0","scripts":{"test":"node --test"}}');
    const files = renderPipeline(resolvePipeline(root, { mode: 'test' }));
    assert.deepEqual(Object.keys(files), [WORKFLOW_FILES.checks]);
    const y = files[WORKFLOW_FILES.checks];
    assert.match(y, /pull_request:\n {4}branches: \['develop', 'main'\]/);
    assert.match(y, /push:\n {4}branches: \['develop'\]/);
    assert.match(y, /run: 'npm install'/);
    assert.match(y, /run: 'npm test'/);
    assert.match(y, /check-commits --range/);
    assert.match(y, /^# Generated by engr-toolbox/);
  });

  test('release mode with trunk branches and npm + docker targets', () => {
    const root = tempDir();
    write(root, 'package.json', '{"version":"2.1.0"}');
    write(root, 'package-lock.json', '{}');
    const p = resolvePipeline(root, { mode: 'release', branches: { development: 'none', main: 'trunk' }, release: { targets: ['github', 'npm', 'docker'] }, build: 'npm run build' });
    const files = renderPipeline(p);
    const checks = files[WORKFLOW_FILES.checks];
    const rel = files[WORKFLOW_FILES.release];
    assert.match(checks, /branches: \['trunk'\]/);
    assert.doesNotMatch(checks, /push:/, 'no development branch to push to');
    assert.match(rel, /push:\n {4}branches: \['trunk'\]/);
    assert.match(rel, /run: 'npm ci'/);
    assert.match(rel, /needs: test/);
    assert.match(rel, /gh release create/);
    assert.match(rel, /npm publish/);
    assert.match(rel, /NPM_TOKEN/);
    assert.match(rel, /docker\/build-push-action@v6/);
    assert.match(rel, /packages: write/);
    assert.match(rel, /refs\/tags\/v\$V/, 'skips versions already tagged');
  });

  test('rejects bad settings', () => {
    const root = tempDir();
    assert.throws(() => resolvePipeline(root, { mode: 'deploy' }), /Unknown pipeline mode/);
    assert.throws(() => resolvePipeline(root, { mode: 'release', release: { targets: ['ftp'] } }), /Unknown release target/);
  });

  test('switching to none removes generated workflows but keeps hand-written ones', () => {
    const root = tempDir();
    write(root, 'package.json', '{"version":"1.0.0"}');
    writePipeline(root, resolvePipeline(root, { mode: 'release' }));
    write(root, '.github/workflows/mine.yml', 'name: mine\n');
    assert.ok(fs.existsSync(path.join(root, WORKFLOW_FILES.release)));
    const r = writePipeline(root, resolvePipeline(root, { mode: 'none' }));
    assert.equal(r.filter(x => x.status === 'removed_stale').length, 2);
    assert.ok(fs.existsSync(path.join(root, '.github/workflows/mine.yml')));
  });
});

describe('release helpers', () => {
  test('version from package.json or VERSION', () => {
    const root = tempDir();
    write(root, 'package.json', '{"version":"3.4.5"}');
    write(root, 'VERSION', 'v1.2.3\n');
    assert.equal(readVersion(root), '3.4.5');
    assert.equal(readVersion(root, 'VERSION'), '1.2.3');
    assert.throws(() => readVersion(root, 'nope.txt'), /not found/);
  });

  test('notes from the CHANGELOG section, else commits since the last tag', () => {
    const root = tempDir();
    write(root, 'CHANGELOG.md', '# Changelog\n\n## [1.1.0] - 2026-11-07\n\n### Added\n\n- Cart\n\n## [1.0.0]\n\n- First\n');
    assert.equal(releaseNotes(root, '1.1.0'), '### Added\n\n- Cart\n');
    const g = gitInit(root);
    g.commit('first [no-ticket]');
    g.run(['tag', 'v1.0.0']);
    write(root, 'a.txt', 'x');
    g.commit('feat: checkout [cart/02]');
    assert.match(releaseNotes(root, '9.9.9'), /Changes since v1\.0\.0:\n\n- feat: checkout \[cart\/02\]/);
  });
});

describe('cli and installer', () => {
  test('pipeline --write saves settings and generates; --check detects edits', () => {
    const root = tempDir();
    write(root, 'package.json', '{"version":"1.0.0"}');
    const run = args => execFileSync('node', [cli, ...args], { cwd: root, encoding: 'utf8', env: { ...process.env, ENGR_NO_DELEGATE: '1' } });
    assert.match(run(['pipeline']), /Pipeline: none/);
    assert.match(run(['pipeline', '--mode', 'release', '--release-targets', 'github,npm', '--write']), /Needs secret: NPM_TOKEN/);
    const saved = JSON.parse(fs.readFileSync(path.join(root, 'engr-toolbox.json'), 'utf8')).pipeline;
    assert.equal(saved.mode, 'release');
    assert.match(run(['pipeline', '--check']), /match/);
    fs.appendFileSync(path.join(root, WORKFLOW_FILES.release), '# edited\n');
    assert.throws(() => run(['pipeline', '--check']), /Command failed/);
    assert.equal(run(['release-version']).trim(), '1.0.0');
  });

  test('init with --pipeline flags writes workflows and next steps mention secrets', () => {
    const root = tempDir();
    const out = execFileSync('node', [cli, 'init', '--yes', '--into', root, '--size', 'small', '--tools', 'claude,codex,opencode', '--pipeline', 'release', '--release-targets', 'github,npm', '--dev-branch', 'dev'], { encoding: 'utf8' });
    assert.match(out, /tools=claude,codex,opencode/);
    assert.match(out, /NPM_TOKEN/);
    assert.ok(fs.existsSync(path.join(root, '.claude/agents/builder.md')));
    assert.ok(fs.existsSync(path.join(root, '.codex/agents/builder.toml')));
    assert.ok(fs.existsSync(path.join(root, '.opencode/agents/builder.md')));
    assert.match(fs.readFileSync(path.join(root, WORKFLOW_FILES.checks), 'utf8'), /branches: \['dev', 'main'\]/);
  });

  test('installing without pipeline options writes no workflows', () => {
    const root = tempDir();
    installAssets({ templateRoot, targetDir: root, size: 'small', tools: ['claude'] });
    assert.ok(!fs.existsSync(path.join(root, '.github/workflows')));
  });
});

describe('custom pipelines', () => {
  test('--custom keeps hand-made workflows untouched; --no-custom --force regenerates', () => {
    const root = tempDir();
    write(root, 'package.json', '{"version":"1.0.0"}');
    const run = args => execFileSync('node', [cli, ...args], { cwd: root, encoding: 'utf8', env: { ...process.env, ENGR_NO_DELEGATE: '1' } });
    run(['pipeline', '--mode', 'release', '--write']);
    const file = path.join(root, WORKFLOW_FILES.checks);
    const handMade = fs.readFileSync(file, 'utf8').split('\n').slice(1).join('\n') + '\n  lint-on-develop: {}\n';
    fs.writeFileSync(file, handMade);
    assert.match(run(['pipeline', '--custom', '--write']), /Custom pipeline/);
    assert.equal(fs.readFileSync(file, 'utf8'), handMade);
    assert.match(run(['pipeline', '--mode', 'test', '--write']), /\(custom\)/);
    assert.ok(fs.existsSync(path.join(root, WORKFLOW_FILES.release)), 'custom mode never removes files');
    assert.match(run(['pipeline', '--check']), /not compared/);
    run(['pipeline', '--no-custom', '--mode', 'release', '--write', '--force']);
    assert.match(fs.readFileSync(file, 'utf8'), /^# Generated by engr-toolbox/);
  });
});

describe('providers', () => {
  test('gitlab: MR checks into develop and main, release and docker on merge to main', () => {
    const root = tempDir();
    write(root, 'package.json', '{"version":"1.0.0"}');
    const files = renderPipeline(resolvePipeline(root, { provider: 'gitlab', mode: 'release', release: { targets: ['release', 'npm', 'docker'] } }));
    assert.deepEqual(Object.keys(files), ['.gitlab-ci.yml']);
    const y = files['.gitlab-ci.yml'];
    assert.match(y, /^# Generated by engr-toolbox/);
    assert.match(y, /stages: \[test, release\]/);
    assert.match(y, /CI_MERGE_REQUEST_TARGET_BRANCH_NAME =~ \/\^\(develop\|main\)\$\//);
    assert.match(y, /CI_COMMIT_BRANCH == "develop"/);
    assert.match(y, /\/releases"/);
    assert.match(y, /npm publish/);
    assert.match(y, /docker-image:/);
    assert.match(y, /services: \['docker:27-dind'\]/, 'colon inside a flow list must be quoted');
    assert.match(y, /dotenv: release\.env/);
    assert.match(y, /check-commits --range "origin\/\$CI_MERGE_REQUEST_TARGET_BRANCH_NAME\.\.HEAD"/);
  });

  test('gitlab test mode has no release stage; tag-only uses the tags API', () => {
    const root = tempDir();
    assert.doesNotMatch(renderPipeline(resolvePipeline(root, { provider: 'gitlab', mode: 'test' }))['.gitlab-ci.yml'], /release:/);
    const y = renderPipeline(resolvePipeline(root, { provider: 'gitlab', mode: 'release', release: { targets: ['tag'] } }))['.gitlab-ci.yml'];
    assert.match(y, /repository\/tags"/);
    assert.match(y, /RELEASE_TOKEN/);
    assert.doesNotMatch(y, /\/releases"/);
  });

  test('github tag-only pushes a tag without a release page; github is an alias of release', () => {
    const root = tempDir();
    const tagOnly = renderPipeline(resolvePipeline(root, { mode: 'release', release: { targets: ['tag'] } }))[WORKFLOW_FILES.release];
    assert.match(tagOnly, /git push origin "v/);
    assert.doesNotMatch(tagOnly, /gh release create/);
    assert.deepEqual(resolvePipeline(root, { mode: 'release', release: { targets: ['github', 'npm'] } }).release.targets, ['release', 'npm']);
  });

  test('other provider generates nothing and switching provider removes the old generated files', () => {
    const root = tempDir();
    write(root, 'package.json', '{"version":"1.0.0"}');
    writePipeline(root, resolvePipeline(root, { mode: 'release' }));
    writePipeline(root, resolvePipeline(root, { provider: 'gitlab', mode: 'release' }));
    assert.ok(!fs.existsSync(path.join(root, WORKFLOW_FILES.checks)), 'github files removed');
    assert.ok(fs.existsSync(path.join(root, '.gitlab-ci.yml')));
    assert.deepEqual(Object.keys(renderPipeline(resolvePipeline(root, { provider: 'other', mode: 'release' }))), []);
    assert.throws(() => resolvePipeline(root, { provider: 'jenkinsfile' }), /Unknown CI provider/);
  });
});
